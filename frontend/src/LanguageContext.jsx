const KK_RU = Object.fromEntries(
  Object.entries(RU_KK).map(([ru, kk]) => [kk, ru])
);


function translateNodeText(value, language) {
  if (!value || !value.trim()) {
    return value;
  }

  const dictionary = language === "kk"
    ? RU_KK
    : KK_RU;

  // A single JSX text node can contain several lines. The old
  // implementation translated only when the WHOLE node exactly matched
  // one dictionary key, which is why multi-line paragraphs stayed Russian.
  // Replace every known phrase inside the node instead.
  let result = value;

  Object.entries(dictionary)
    .sort(([a], [b]) => b.length - a.length)
    .forEach(([source, target]) => {
      if (result.includes(source)) {
        result = result.split(source).join(target);
      }
    });

  return result;
}


function translatePage(language) {
  const root = document.getElementById("root");

  if (!root) {
    return;
  }

  const walker = document.createTreeWalker(
    root,
    NodeFilter.SHOW_TEXT
  );

  const textNodes = [];

  while (walker.nextNode()) {
    textNodes.push(walker.currentNode);
  }

  textNodes.forEach((node) => {
    node.nodeValue = translateNodeText(
      node.nodeValue,
      language
    );
  });

  root
    .querySelectorAll("[placeholder]")
    .forEach((element) => {
      const value = element.getAttribute("placeholder");
      const dictionary = language === "kk"
        ? RU_KK
        : KK_RU;

      if (dictionary[value]) {
        element.setAttribute(
          "placeholder",
          dictionary[value]
        );
      }
    });

  document.documentElement.lang =
    language === "kk" ? "kk" : "ru";
}


export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(
    () => localStorage.getItem("smartQalaLanguage") || "ru"
  );

  function setLanguage(nextLanguage) {
    const normalized = nextLanguage === "kk"
      ? "kk"
      : "ru";

    localStorage.setItem(
      "smartQalaLanguage",
      normalized
    );

    setLanguageState(normalized);
  }

  useEffect(() => {
    translatePage(language);

    const observer = new MutationObserver(() => {
      translatePage(language);
    });

    const root = document.getElementById("root");

    if (root) {
      observer.observe(root, {
        childList: true,
        subtree: true,
      });
    }

    return () => observer.disconnect();
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      isKazakh: language === "kk",
    }),
    [language]
  );

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}


export function useLanguage() {
  const context = useContext(LanguageContext);

  if (!context) {
    throw new Error(
      "useLanguage must be used inside LanguageProvider"
    );
  }

  return context;
}
